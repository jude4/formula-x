import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'formula-x-blender-test-'));
function blender(script, args = [], success = true) {
  const result = spawnSync('blender', ['--background', '--factory-startup', '--python-exit-code', '1', '--python', script, '--', ...args], { encoding: 'utf8', env: { ...process.env, FX_TEST_DIR: directory }, maxBuffer: 4e6 });
  if (result.error) throw result.error;
  if ((result.status === 0) !== success) throw Error(result.stdout + result.stderr);
}
const hash = (file) => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
try {
  blender('tests/blender/preparation_fixture.py');
  const source = path.join(directory, 'fixture.blend'); const sourceHash = hash(source);
  const license = path.join(directory, 'license.json');
  fs.writeFileSync(license, JSON.stringify({ asset: 'Original triangle test fixture', creator: 'FORMULA X test code', license: 'CC0-1.0', source: 'tests/blender/preparation_fixture.py', verified_by: 'Original geometry generated by this test' }));
  const output = path.join(directory, 'fixture.glb'); const report = path.join(directory, 'report.json');
  const args = ['--source', source, '--report', report, '--output', output, '--license-record', license];
  blender('scripts/blender/prepare_vehicle.py', args);
  assert.equal(hash(source), sourceHash, 'Preparation must not mutate source');
  assert.deepEqual(JSON.parse(fs.readFileSync(report)).issues, []);
  const bytes = fs.readFileSync(output);
  const gltf = JSON.parse(bytes.subarray(20, 20 + bytes.readUInt32LE(12)).toString());
  const panel = gltf.nodes.find((node) => node.extras?.fx_component_id === 'fixture.panel');
  assert(panel, 'Export must retain stable component IDs');
  assert.equal(panel.extras.fx_category, 'test-only');
  assert.equal(gltf.meshes.length, 1);
  blender('scripts/blender/prepare_vehicle.py', args, false);
  assert.equal(hash(source), sourceHash);
  blender('scripts/blender/prepare_vehicle.py', ['--source', source, '--report', path.join(directory, 'missing-license.json'), '--output', path.join(directory, 'blocked.glb')], false);
  assert(!fs.existsSync(path.join(directory, 'blocked.glb')), 'Unlicensed export must be blocked');
  console.log('Blender preparation passed: exported metadata, unchanged source, overwrite protection, missing-license rejection.');
} finally { fs.rmSync(directory, { recursive: true, force: true }); }
