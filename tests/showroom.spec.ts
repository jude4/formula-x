import { test, expect } from '@playwright/test';
test('showroom loads and camera controls work without runtime errors', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:5173');
  await expect(page.getByRole('button', { name: 'Enter the experience' })).toBeEnabled({ timeout: 60000 });
  await expect(page.locator('canvas')).toBeVisible();
  await page.waitForTimeout(1800);
  await page.screenshot({ path: '/tmp/formula-x-desktop.png' });
  await page.getByRole('button', { name: 'Enter the experience' }).click();
  await expect(page.getByText('THE STUDIO IS YOURS')).toBeVisible();
  await page.getByRole('button', { name: 'Perspective', exact: true }).click();
  const beforeView = await page.locator('canvas').screenshot();
  await page.getByRole('button', { name: 'Front', exact: true }).click();
  await page.waitForTimeout(1600);
  const afterView = await page.locator('canvas').screenshot();
  expect(beforeView.equals(afterView)).toBe(false);
  await expect(page.getByRole('button', { name: 'Front', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Toggle automatic rotation' }).click();
  await expect(page.getByRole('button', { name: 'Toggle automatic rotation' })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'Reset camera' }).click();
  await expect(page.getByRole('button', { name: 'Toggle automatic rotation' })).toHaveAttribute('aria-pressed', 'false');
  await expect(page.getByRole('button', { name: 'Perspective', exact: true })).toBeVisible();
  await page.getByRole('button', { name: /Render quality/ }).click();
  await expect(page.getByRole('button', { name: /Render quality: balanced/ })).toBeVisible();
  await page.getByRole('button', { name: 'The project' }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  const canvas = page.locator('canvas'); const b = (await canvas.boundingBox())!;
  await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2);
  await page.mouse.down(); await page.mouse.move(b.x + b.width / 2 + 100, b.y + b.height / 2 + 30, { steps: 12 }); await page.mouse.up();
  await page.mouse.wheel(0, 120);
  await expect(page.locator('.webgl-fallback')).not.toBeVisible();
  expect(errors).toEqual([]);
});
test('mobile layout remains usable', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('http://127.0.0.1:5173');
  await expect(page.getByRole('button', { name: 'Enter the experience' })).toBeEnabled({ timeout: 60000 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  await page.screenshot({ path: '/tmp/formula-x-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Perspective', exact: true }).click();
  await page.getByRole('button', { name: 'Rear', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Rear', exact: true })).toBeVisible();
});
